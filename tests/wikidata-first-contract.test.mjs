import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const contract=read("data/wikidata-first-entity-contract.json");
const core=read("knowledge-core.json");
const ai=read("ai-entry.json");
const graph=read("person-authority.jsonld")["@graph"];
const agent=read(".well-known/agent.json");
assert.equal(agent.canonical,"https://www.norbertbanhalmi.com/");
for(const url of agent.read)assert.ok(url.startsWith("/api/v1/"));
assert.equal(contract.entities.person.wikidata,"Q56391118");
assert.equal(contract.entities.legalOrganization.wikidata,"Q138425941");
assert.equal(contract.entities.brand.wikidata,null);
assert.equal(core.primaryPerson.wikidata,contract.entities.person.wikidataUrl);
assert.equal(core.primaryOrganization.wikidata,contract.entities.legalOrganization.wikidataUrl);
assert.equal(ai.identity.person.wikidata,contract.entities.person.wikidataUrl);
assert.equal(ai.identity.organization.wikidata,contract.entities.legalOrganization.wikidataUrl);
assert.ok(core.wikidataFirstContract && ai.wikidataFirstContract);
const person=graph.find(n=>n["@type"]==="Person" && n["@id"]===contract.entities.person.canonicalId);
assert.ok(person);
assert.ok(person.sameAs.includes(contract.entities.person.wikidataUrl));
assert.ok(!person.sameAs.includes(contract.entities.legalOrganization.wikidataUrl));
assert.ok(!person.sameAs.includes("https://www.banhalmi.art/"));
console.log("Wikidata-first identity, source ownership and schema semantics: PASS");
